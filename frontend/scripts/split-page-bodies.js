// Splits src/content/pageBodies.js (the editable source) into one small file per page, so each
// page downloads only its own text. Runs automatically before every build.
const fs = require("fs");
const path = require("path");

const SRC = path.join(__dirname, "..", "src", "content", "pageBodies.js");
const OUT = path.join(__dirname, "..", "src", "content", "bodies");
const code = fs.readFileSync(SRC, "utf8").replace(/^export const /gm, "const ");
// eslint-disable-next-line no-new-func
const { pageBodies, communityFaq } = new Function(`${code}\nreturn { pageBodies, communityFaq };`)();

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });
const entries = Object.entries(pageBodies);
const name = (p) => p.replace(/^\//, "").replace(/[^A-Za-z0-9-]/g, "_") || "home";
for (const [p, body] of entries) fs.writeFileSync(path.join(OUT, `${name(p)}.json`), JSON.stringify(body));
const loaders = entries.map(([p]) => `  ${JSON.stringify(p)}: () => import(/* webpackChunkName: "body-${name(p)}" */ "./${name(p)}.json"),`).join("\n");
fs.writeFileSync(path.join(OUT, "index.js"), `// Generated by scripts/split-page-bodies.js from ../pageBodies.js — edit that file instead.\nconst loaders = {\n${loaders}\n};\nexport default loaders;\n`);
fs.writeFileSync(path.join(OUT, "shared.js"), `// Generated by scripts/split-page-bodies.js — edit ../pageBodies.js instead.\nexport const communityFaq = ${JSON.stringify(communityFaq)};\n`);
console.log(`Page bodies: ${entries.length} pages split`);
